// Renders src/demo/spec.ts into supabase/seed.sql.
//   node scripts/seed-sql.ts
// The output is idempotent: it removes earlier sample rows first.
import { writeFileSync } from "node:fs";
import { COMPANIES, REVIEW_THREADS, TASKS, TEMPLATES, type Who } from "../src/demo/spec.ts";

// Team members are looked up by display name so no real address lives in this repository.
const NAME: Record<Who, string> = { advik: "Advik", neel: "Neel", raphy: "Raphy" };
const q = (v: string | null | undefined) => (v == null ? "null" : `'${v.replace(/'/g, "''")}'`);
const who = (w: Who) => `(select id from public.allowed_users where display_name = ${q(NAME[w])})`;
const ago = (days: number, hour = 10) => `(date_trunc('day', now()) - interval '${days} days' + interval '${hour} hours')`;
const company = (name: string) => `(select id from public.companies where name = ${q(name)} and is_sample)`;
const contact = (name: string) => `(select id from public.contacts where name = ${q(name)} and company_id in (select id from public.companies where is_sample) limit 1)`;
const template = (key: string) => {
  const t = TEMPLATES.find((x) => x.key === key)!;
  return `(select id from public.templates where name = ${q(t.name)} and version = ${t.version} and is_sample)`;
};

const out: string[] = [
  "-- Sample data for PAIDI CRM. Generated by scripts/seed-sql.ts; do not edit by hand.",
  "-- Every company, person and email address here is fictional.",
  "begin;",
  "delete from public.tasks where is_sample;",
  "delete from public.companies where is_sample;",
  "delete from public.templates where is_sample;",
  "",
];

for (const t of TEMPLATES) {
  out.push(`insert into public.templates (name, type, version, subject, body, active, is_sample, created_by, created_at) values (${q(t.name)}, ${q(t.type)}, ${t.version}, ${q(t.subject)}, ${q(t.body)}, ${t.active}, true, ${who(t.by)}, ${ago(95)});`);
}
out.push("");

for (const c of COMPANIES) {
  const lastTouch = c.touches.reduce<number | null>((m, t) => (m == null || t.daysAgo < m ? t.daysAgo : m), null);
  out.push(`insert into public.companies (name, website, domain, industry, employee_count, location, source, source_detail, owner_id, created_by, stage, lost_reason, is_sample, created_at, stage_changed_at) values (${q(c.name)}, ${q(`https://${c.domain}`)}, ${q(c.domain)}, ${q(c.industry)}, ${c.employees}, ${q(c.location)}, ${q(c.source)}, ${q(c.sourceDetail)}, ${who(c.owner)}, ${who(c.owner)}, ${q(c.stage)}, ${q(c.lostReason)}, true, ${ago(c.createdDaysAgo)}, ${ago(lastTouch ?? c.createdDaysAgo)});`);
  const [first, ...rest] = c.contact.name.toLowerCase().split(" ");
  out.push(`insert into public.contacts (company_id, name, title, email, referral_source, owner_id, created_by, created_at) values (${company(c.name)}, ${q(c.contact.name)}, ${q(c.contact.title)}, ${q(`${first}.${rest.join("")}@${c.domain}`)}, ${q(c.contact.referral)}, ${who(c.owner)}, ${who(c.owner)}, ${ago(c.createdDaysAgo)});`);
  out.push(`insert into public.research (company_id, contact_id, hook, common_ground, tool_idea, created_by, created_at) values (${company(c.name)}, ${contact(c.contact.name)}, ${q(c.hook)}, ${q(c.common)}, ${q(c.idea)}, ${who(c.owner)}, ${ago(c.createdDaysAgo)});`);

  // Replace the single trigger-written "Created" row with the full stage history.
  out.push(`delete from public.stage_changes where company_id = ${company(c.name)};`);
  const path: [string, number, string?][] = [...(c.path ?? []), [c.stage, lastTouch ?? c.createdDaysAgo]];
  path.forEach(([stage, daysAgo, reason], j) => {
    const prev = j === 0 ? null : path[j - 1][0];
    const auto = !!reason || (j === path.length - 1 && j > 0 && ["contacted", "followed_up", "responded", "nurture"].includes(stage));
    const text = reason ?? (j === 0 ? "Created" : auto
      ? (stage === "nurture" ? "No reply after 3 touches" : stage === "responded" ? "Reply received" : "First email sent")
      : null);
    out.push(`insert into public.stage_changes (company_id, from_stage, to_stage, automatic, reason, changed_by, created_at) values (${company(c.name)}, ${q(prev)}, ${q(stage)}, ${auto}, ${q(text)}, ${auto ? "null" : who(c.owner)}, ${ago(j === 0 ? c.createdDaysAgo : daysAgo)});`);
  });

  c.touches.forEach((t, j) => {
    const email = t.type === "email_out" || t.type === "email_in";
    const msgId = `sample-${c.domain}-${j}`;
    out.push(`insert into public.interactions (company_id, contact_id, type, occurred_at, team_member_id, subject, summary, template_id, outcome, source, gmail_thread_id, gmail_message_id) values (${company(c.name)}, ${contact(c.contact.name)}, ${q(t.type)}, ${ago(t.daysAgo, 9 + j)}, ${who(t.by)}, ${q(t.subject)}, ${q(t.summary)}, ${t.template ? template(t.template) : "null"}, ${q(t.outcome)}, ${email ? "'import'" : "'manual'"}, ${email ? q(`sample-${c.domain}`) : "null"}, ${email ? q(msgId) : "null"});`);
    if (t.intel) {
      const i = t.intel;
      out.push(`insert into public.call_intel (interaction_id, why_took_call, pain_points, objections, lost_interest_at, asks, next_step) select id, ${q(i.why_took_call)}, ${q(i.pain_points)}, ${q(i.objections)}, ${q(i.lost_interest_at)}, ${q(i.asks)}, ${q(i.next_step)} from public.interactions where company_id = ${company(c.name)} and summary = ${q(t.summary)};`);
    }
  });
  out.push("");
}

for (const t of TASKS) {
  out.push(`insert into public.tasks (title, description, assignee_id, due_date, status, priority, company_id, is_sample, created_by) values (${q(t.title)}, ${q(t.description)}, ${who(t.assignee)}, current_date + ${t.dueInDays}, ${q(t.status)}, ${q(t.priority)}, ${t.company ? company(t.company) : "null"}, true, ${who(t.assignee)});`);
}
out.push("", "-- The hourly follow-up job creates the automatic follow-up tasks for overdue prospects.", "select private.run_followups();", "commit;", "");
void REVIEW_THREADS; // Review-queue samples exist only in demo mode: real ones need a connected inbox.

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), out.join("\n"));
console.log(`Wrote supabase/seed.sql (${out.length} lines)`);
